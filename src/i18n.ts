const dicts: Record<LangCode, Record<string, string>> = { en, ru };

function savedLang(): LangCode {
  try {
    const l = localStorage.getItem('lang');
    return l === 'ru' ? 'ru' : 'en';
  } catch {
    return 'en';
  }
}

let current: LangCode = savedLang();
const listeners = new Set<() => void>();

export function getLang(): LangCode {
  return current;
}

export function setLang(l: string) {
  const next: LangCode = l === 'ru' ? 'ru' : 'en';
  if (next === current) return;
  current = next;
  try {
    localStorage.setItem('lang', current);
  } catch {
    /* ignore */
  }
  listeners.forEach((cb) => cb());
}

export function t(key: string): string {
  return dicts[current][key] ?? key;
}

export function tx(key: string, params: Record<string, string | number>): string {
  let s = t(key);
  for (const [k, v] of Object.entries(params)) {
    s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export function useLang(): LangCode {
  return useSyncExternalStore(
    (cb) => {
      listeners.add(cb);
      return () => {
        listeners.delete(cb);
      };
    },
    getLang,
  );
}

